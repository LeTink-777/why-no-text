export type Subject = "he" | "she";

export const SUBJECT: Record<Subject, { toggle: string; nom: string; gen: string; verb: string }> = {
  he: { toggle: "Про него", nom: "он", gen: "его", verb: "не пишет" },
  she: { toggle: "Про неё", nom: "она", gen: "её", verb: "не пишет" },
};

export function isSubject(value: string | undefined): value is Subject {
  return value === "he" || value === "she";
}

