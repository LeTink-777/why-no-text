export function topReason(days: DaysId, tone: ToneId, status: StatusId): Reason {
  if (tone === "conflict") return REASONS[2];
  if (tone === "good" && days === "d3") return REASONS[0];
  if (tone === "good" && status === "dating") return REASONS[5];
  if (tone === "neutral" && status === "new" && days === "week") return REASONS[3];
  if (days === "week") return REASONS[4];
  return REASONS[1];
}

